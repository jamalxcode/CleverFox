// Looks up each mapped publisher on Wikidata and writes data/publishers.json:
// Hugging Face account -> { name, qid, country (ISO), source }. Run by the "Publishers" workflow
// (Wikidata rate-limits shared connections), then review the result before relying on it.
// A match is kept only if Wikidata describes it as an organisation and gives a country.
//
// Usage: node tools/publishers.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const API = 'https://www.wikidata.org/w/api.php?format=json&';
const UA = { 'User-Agent': 'CleverFoxCatalog/0.1 (https://github.com/jamalxcode/cleverfox)' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function get(url) {
  for (let i = 0; i < 6; i++) {
    const res = await fetch(url, { headers: UA });
    if (res.ok) { await sleep(1200); return res.json(); }
    await sleep(15000 * (i + 1));
  }
  throw new Error(`Wikidata failed: ${url}`);
}
const ids = (e, p) => (e?.claims?.[p] || []).map((c) => c.mainsnak?.datavalue?.value?.id).filter(Boolean);
async function batch(list, props) {
  const out = {};
  for (let i = 0; i < list.length; i += 45) Object.assign(out, (await get(`${API}action=wbgetentities&languages=en&props=${props}&ids=${list.slice(i, i + 45).join('%7C')}`)).entities);
  return out;
}
const ORG_WORDS = /(company|corporation|organi[sz]ation|university|institute|laborator|lab\b|academy|startup|enterprise|non-profit|nonprofit|research|foundation|conglomerate|business|government agency|centre|center|developer|firm|subsidiary)/i;

const map = JSON.parse(readFileSync(join(root, 'data', 'publisher-map.json'), 'utf8')).publishers;
const names = [...new Set(Object.values(map).map((m) => m.name))];
const qidOf = {};
for (const m of Object.values(map)) if (m.qid) qidOf[m.name] = m.qid;
// Up to 5 search hits per name: the first that Wikidata describes as an organisation with a country wins (the top hit
// alone was often a person, a product or a place, which left 13 mapped publishers without a country).
const candidates = {};
for (const n of names) {
  if (qidOf[n]) { candidates[n] = [qidOf[n]]; continue; }
  const r = (await get(`${API}action=wbsearchentities&language=en&type=item&limit=5&search=${encodeURIComponent(n)}`)).search || [];
  candidates[n] = r.map((x) => x.id);
}
const ents = await batch([...new Set(Object.values(candidates).flat())], 'claims%7Clabels%7Cdescriptions');
const hqs = [...new Set(Object.values(ents).filter((e) => !ids(e, 'P17').length).flatMap((e) => ids(e, 'P159').slice(0, 1)))];
const hqe = hqs.length ? await batch(hqs, 'claims') : {};
const countryOf = (e) => ids(e, 'P17')[0] || ids(hqe[ids(e, 'P159')[0]], 'P17')[0] || null;
const cids = [...new Set(Object.values(ents).map(countryOf).filter(Boolean))];
const ce = await batch(cids, 'claims');
const iso = Object.fromEntries(cids.map((c) => [c, ce[c]?.claims?.P297?.[0]?.mainsnak?.datavalue?.value || null]));

for (const n of names) {
  if (qidOf[n]) continue;
  const ok = candidates[n].find((q) => ents[q] && ORG_WORDS.test(ents[q].descriptions?.en?.value || '') && iso[countryOf(ents[q])]);
  qidOf[n] = ok || candidates[n][0];
}
const out = {}; const skipped = [];
for (const [account, m] of Object.entries(map)) {
  const q = qidOf[m.name]; const e = q && ents[q];
  const desc = e?.descriptions?.en?.value || '';
  const country = e && iso[countryOf(e)];
  if (!e || !country || (!m.qid && !ORG_WORDS.test(desc))) { skipped.push(`${account} (${m.name}): ${q || 'no match'} ${desc}`); continue; }
  out[account] = { name: (m.keep_name ? m.name : e.labels?.en?.value) || m.name, qid: q, description: desc, country, source: `https://www.wikidata.org/wiki/${q}` };
}
writeFileSync(join(root, 'data', 'publishers.json'), JSON.stringify({ _about: 'Generated by tools/publishers.mjs from Wikidata. Review before relying on it; fix matches in data/publisher-map.json.', publishers: out }, null, 1) + '\n');
console.log(`${Object.keys(out).length} publishers with a country; skipped ${skipped.length}:\n  ${skipped.join('\n  ')}`);
for (const [a, p] of Object.entries(out)) console.log(`${a.padEnd(18)} ${p.country}  ${p.name} | ${p.description}`);
